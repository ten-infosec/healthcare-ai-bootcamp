// 동등 비교(==): 두 값이 같은지 비교
// 결과 -> boolean

console.log(10 == 10);      // true

// == 는 자료형이 다르면 자동으로 변환해서 비교
// (숫자 vs 문자열이면 문자열을 숫자로 바꿈)
console.log(10 == "10");    // true
console.log(10 == "10.0");  // true  ← "10.0"이 숫자 10으로 바뀜

// 일치 비교(===): 값 + 자료형까지 비교 (변환 없음, 권장)
console.log(10 === 10);     // true
console.log(10 === "10");   // false

// 다름 비교: != 는 == 의 반대, !== 는 === 의 반대
console.log(10 != "10");    // false  (변환 후 같으니까)
console.log(10 !== "10");   // true   (자료형이 다르니까)

// [정리]
// ==  / != : 값만 비교 (자동 변환 O) → 버그 위험
// === / !==: 값 + 자료형 비교 (자동 변환 X) → 실무에서 기본으로 사용
// 파이썬의 == 는 JS의 === 처럼 자동 변환을 안 함 (10 == "10" → False)